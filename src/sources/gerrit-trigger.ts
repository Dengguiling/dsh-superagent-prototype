/** Gerrit source kind: normalizes review comments and change messages into domain Triggers. */
import { key, type ChannelRef, type ThreadRef, type Trigger } from '../core/index.ts'
import { sameName } from '../infra/text.ts'
import { accountOf } from './gerrit-read.ts'

export const SOURCE = 'gerrit'
/** The Redmine Source owns the issue a tracked change answers; its Trigger carries that Thread too. */
const ISSUE = 'redmine'
/** Gerrit reply address: the change a review message goes to, and the project it is in. */
export const gerritChannel = (change: number, project = ''): ChannelRef =>
  ({ source: SOURCE, thread: `gerrit:${change}`, address: { change: String(change), project } })
/**
 * The Threads of a Trigger of a change: the change first, whose primary Thread hosts its assessment, then the Redmine issue
 * its commit message names. A company has many repositories, so the issue is what binds a change to its ticket, and the
 * second Thread is how a review comment on somebody else's patch reaches that ticket too.
 */
const threadsOf = (change: { _number: number }, issue?: string): ThreadRef[] =>
  [{ source: SOURCE, id: String(change._number) }, ...issue ? [{ source: ISSUE, id: issue }] : []]
/**
 * True when an account is a robot rather than a person. Gerrit's robots carry a name such as `Gerrit Robot` or
 * `review-bot`; their comments never authorize work on their own.
 */
export const isRobot = (name: string | undefined): boolean => !!name && /\b(bot|robot|jenkins|continuous)\b/i.test(name)
/**
 * Builds the Trigger of one review comment on a change. A comment the agent itself wrote, or a robot's, produces no
 * Trigger of its own; the agent's own comments are its work, not a request. `issue` is the Redmine issue the change's
 * commit message names, when it names one.
 */
export function commentTrigger(change: { _number: number; id: string; project: string; branch: string; topic?: string | null },
  comment: { id: string; message: string; author?: { username?: string; name?: string } | null; created?: string | null, path?: string | null; line?: number | null },
  agent: string, httpUrl: string, issue?: string): Trigger | undefined {
  const author = accountOf(comment.author)
  if (agent && sameName(author, agent)) return undefined
  const text = comment.message.trim()
  if (!text) return undefined
  const place = comment.path ? `${comment.path}${comment.line != null ? `:${comment.line}` : ''}` : ''
  return { id: key('gerrit-comment', change.id, comment.id), source: SOURCE,
    threads: threadsOf(change, issue),
    actor: { source: SOURCE, id: author }, human: !isRobot(author),
    at: comment.created ?? new Date().toISOString(), text: place ? `${place}\n\n${text}` : text,
    channel: gerritChannel(change._number, change.project), url: `${httpUrl.replace(/\/+$/, '')}/#/c/${change.project}/+/${change._number}`,
    meta: { kind: 'comment', changeNumber: change._number, changeId: change.id, project: change.project, branch: change.branch,
      topic: change.topic ?? '', commentId: comment.id, ...issue ? { issueId: Number(issue) } : {},
      ...comment.path ? { path: comment.path, line: comment.line ?? null } : {} } }
}
/**
 * Builds the Trigger of a change message, such as the one Gerrit writes when a change is merged or abandoned. It is
 * machine-made, so it never authorizes work on its own. `issue` is the Redmine issue the change answers, when it names one.
 */
export function messageTrigger(change: { _number: number; id: string; project: string; branch: string; topic?: string | null },
  message: { id?: string | null; message?: string | null; author?: { username?: string; name?: string } | null; date?: string | null; tag?: string | null },
  agent: string, httpUrl: string, issue?: string): Trigger | undefined {
  const text = (message.message ?? '').trim()
  if (!text) return undefined
  // Gerrit's own notes about a patch set, such as the one that says it was uploaded, ask for nothing.
  if (message.tag?.startsWith('autogenerated:')) return undefined
  const author = accountOf(message.author)
  // The agent's own note on its change is its work, not a request.
  if (agent && sameName(author, agent)) return undefined
  return { id: key('gerrit-message', change.id, message.id ?? text), source: SOURCE,
    threads: threadsOf(change, issue),
    actor: { source: SOURCE, id: author }, human: !isRobot(author),
    at: message.date ?? new Date().toISOString(), text,
    channel: gerritChannel(change._number, change.project), url: `${httpUrl.replace(/\/+$/, '')}/#/c/${change.project}/+/${change._number}`,
    meta: { kind: 'message', changeNumber: change._number, changeId: change.id, project: change.project, branch: change.branch,
      topic: change.topic ?? '', ...issue ? { issueId: Number(issue) } : {} } }
}
/**
 * Reads the task a change answers from the trailers of its commit message. Gerrit's convention is `Issue:`, `Bug:`, or
 * `Feature:` followed by the number of the task; a corporate deployment names its Redmine issue there.
 */
export function issueOf(message: string): string | undefined {
  const match = /(?:^|\n)\s*(?:Issue|Bug|Feature|Redmine|Redmine-Issue)\s*:\s*#?(\d+)/i.exec(message)
  return match?.[1]
}
/** The topic of a change, which the agent names after the ticket it belongs to. */
export const topicOf = (change: { topic?: string | null }): string => change.topic ?? ''
